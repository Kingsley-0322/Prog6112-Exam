    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        try {
    String customerName = txtCustomer.getText();
    String productName = (String) cmbProduct.getSelectedItem();
    double price = Double.parseDouble(txtPrice.getText());

    // Calculation Requirements - from Page 8
    double vat = price * 0.15; // 15%
    double commission = price * 0.05; // 5%
    double total = price + vat + commission;

    String message = "Customer Name: " + customerName + "\n"
            + "Product: " + productName + "\n"
            + "VAT: R " + vat + "\n"
            + "COMMISSION: R " + commission + "\n"
            + "TOTAL: R " + total;

    JOptionPane.showMessageDialog(this, message);

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "Please enter a valid price! e.g. 3500");
}
    }//GEN-LAST:event_btnProcessActionPerformed

